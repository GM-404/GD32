/**
 * @brief  目前暂时不用
 * @brief  初始化选定的窗函数。必须在开始信号处理前调用一次。窗函数类型选择（矩形窗或汉明窗）。
 * 汉明窗:w(n) = 0.54 - 0.46 * cos(2*pi*n / (N-1))
 */
void initialize_windowing(WindowType type)
{
    const int N = RADAR_CHIRP_POINTS;
    
    // 如果是矩形窗或 N=1，则无需计算，直接返回。
    if (type == WINDOW_RECTANGULAR) {
        //printf("Windowing set to Rectangular (No Window) mode.\n");
        return;
    }
    if (N <= 1) {
        if (N == 1) {
            s_current_window[0] = 1.0;
        }
        return;
    }

    const float N_minus_1 = (float)(N - 1);

    for (int n = 0; n < N; ++n) {
        // 计算公式中的角度项
        float angle = 2.0 * M_PI * (float)n / N_minus_1;
        float cos_val = cos(angle);
        
        if (type == WINDOW_HAMMING) {
            // 汉明窗: w(n) = 0.54 - 0.46 * cos(angle)
            s_current_window[n] = 0.54 - 0.46 * cos_val;
            printf("%d, %f\n", n, s_current_window[n]); // 打印当前窗函数值.\n");
        } 
        else {
            // 默认或未知类型，设置为 1.0 (等效于矩形窗)
            s_current_window[n] = 1.0; 
        }
    }
    
    printf("(N=%d) initialized successfully.\n",  N);
}
/**
 * @brief 将选定的窗函数应用于输入数据。
 * @param type 选定的窗类型。
 * @param input_data 原始 int8_t 数据。
 * @param output_windowed 加窗后的 float 数据。
 */
void apply_range_windowing(
    WindowType type,
    const int8_t input_data[RADAR_ANT_COUNT][RADAR_CHIRP_COUNT][RADAR_CHIRP_POINTS],
    float output_windowed[RADAR_ANT_COUNT][RADAR_CHIRP_COUNT][RADAR_CHIRP_POINTS])
{
    const int N_ANT = RADAR_ANT_COUNT;
    const int N_CHIRP = RADAR_CHIRP_COUNT;
    const int N_POINTS = RADAR_CHIRP_POINTS;

    // 矩形窗（乘 1）的处理：只进行 int8_t 到 float 的类型转换
    if (type == WINDOW_RECTANGULAR) {
        for (int ant = 0; ant < N_ANT; ++ant) {
            for (int chirp = 0; chirp < N_CHIRP; ++chirp) {
                for (int i = 0; i < N_POINTS; ++i) {
                    // 仅进行类型转换，等效于乘 1
                    output_windowed[ant][chirp][i] = (float)input_data[ant][chirp][i];
                }
            }
        }
        return;
    }
    
    // 汉明窗的处理
    const float *window = s_current_window;

    for (int ant = 0; ant < N_ANT; ++ant) {
        for (int chirp = 0; chirp < N_CHIRP; ++chirp) {
            for (int i = 0; i < N_POINTS; ++i) {
                // 1. int8_t 转换为 float
                float data_val = (float)input_data[ant][chirp][i];
                
                // 2. 应用窗函数（乘法）
                output_windowed[ant][chirp][i] = data_val * window[i];
            }
        }
    }
}
/**
 * @brief 在2D FFT之前，对1D FFT结果应用多普勒维（Chirp维）窗函数。
 * 执行操作: data[ant][chirp][range] = data[ant][chirp][range] * s_vwin_window[chirp]
 * @param data 1D FFT 输出数据，原地修改，维度为 [Ant][Chirp][RangeBins][Re/Im]。
 */
void apply_doppler_windowing(RadarFFT1DOutput data)
{
    // 获取关键维度
    const int N_ANT = RADAR_ANT_COUNT;
    const int N_CHIRP = RADAR_CHIRP_COUNT;      // 速度维长度
    // 距离门数量
    const int NUM_RANGE_BINS = RANGE_BINS;
    
    // 获取窗函数
    const float *v_win = s_vwin_window;

    // 1. 遍历天线 (Antenna)
    for (int ant = 0; ant < N_ANT; ++ant) {
        // 2. 遍历距离门 (Range Bins, 对应 MATLAB 中的 mm 循环)
        for (int range = 0; range < NUM_RANGE_BINS; ++range) { 
            
            // 3. 遍历 Chirp (速度维, 对应 MATLAB 中的 rangFft)
            for (int chirp = 0; chirp < N_CHIRP; ++chirp) { 
                
                // 获取窗函数值
                float window_val = v_win[chirp];
                
                // 核心操作：原地乘以窗函数值 (应用于实部和虚部)
                // data[ant][chirp][range][0] 是实部
                data[ant][chirp][range][0] *= window_val; 
                
                // data[ant][chirp][range][1] 是虚部
                data[ant][chirp][range][1] *= window_val; 
            }
        }
    }
}
