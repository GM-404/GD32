int main() {
    printf("--- Pure C DFT (O(N^2)) 1D FFT Test ---\n");
    printf("Input Points (N): %u, Output Complex Bins (N/2+1): %u\n", 
           RADAR_CHIRP_POINTS, DFT_OUTPUT_COMPLEX_POINTS);

    // 1. 初始化 DFT
    if (dft_init() != 0) {
        printf("DFT Initialization failed.\n");
        return -1;
    }

    // 2. 准备输出缓冲区
    complex_float output_bins[DFT_OUTPUT_COMPLEX_POINTS];

    // 3. 执行 1D DFT (调用您实现的 dft_1d_process)
    printf("Starting DFT calculation...\n");
    if (dft_1d_process(TEST_INPUT_CHIRP, output_bins) != 0) {
        printf("DFT Process failed.\n");
        return -1;
    }
    printf("DFT Calculation complete.\n");

    // 4. 打印结果 (幅值/Magnitude)
    printf("\n--- DFT Magnitude Results (First 10 Bins) ---\n");
    printf("Bin Index | Real Part | Imag Part | Magnitude\n");
    printf("----------|-----------|-----------|------------\n");

    // 打印前 10 个距离点结果
    for (uint32_t k = 0; k < 10; k++) {
        float R = output_bins[k].real;
        float I = output_bins[k].imag;
        // 幅值 Magnitude = sqrt(R^2 + I^2)
        float magnitude = sqrtf(R * R + I * I);

        printf("%-9u | %-9.2f | %-9.2f | %-10.2f\n", 
               k, R, I, magnitude);
    }
    
    printf("...\n");
    printf("\n测试完成。\n");

    return 0;
}
